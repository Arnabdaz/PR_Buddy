# TestBraceMatcher — robustness against tricky brace-hiding constructs
# ---------------------------------------------------------------------------


class TestBraceMatcher:
    def test_end_line_is_real_closing_brace(self) -> None:
        # TrickyFunc starts at line 3 and its real } is on line 13
        a = GoAdapter()
        by_name = {s.name: s for s in a.list_symbols(_TRICKY_SRC)}
        assert "TrickyFunc" in by_name
        tf = by_name["TrickyFunc"]
        assert tf.start_line == 3
        assert tf.end_line == 13

    def test_extract_contains_string_brace(self) -> None:
        a = GoAdapter()
        src = a.extract_symbol_sources(_TRICKY_SRC)
        assert '"a string with } brace"' in src["TrickyFunc"]

    def test_extract_contains_line_comment_brace(self) -> None:
        a = GoAdapter()
        src = a.extract_symbol_sources(_TRICKY_SRC)
        assert "// comment with }" in src["TrickyFunc"]

    def test_extract_contains_raw_string_brace(self) -> None:
        a = GoAdapter()
        src = a.extract_symbol_sources(_TRICKY_SRC)
        assert "`raw } str`" in src["TrickyFunc"]

    def test_extract_contains_rune_brace(self) -> None:
        a = GoAdapter()
        src = a.extract_symbol_sources(_TRICKY_SRC)
        assert "'}'" in src["TrickyFunc"]

    def test_extract_contains_nested_closure(self) -> None:
        a = GoAdapter()
        src = a.extract_symbol_sources(_TRICKY_SRC)
        assert "func() int" in src["TrickyFunc"]

    def test_extract_starts_with_func_keyword(self) -> None:
        a = GoAdapter()
        src = a.extract_symbol_sources(_TRICKY_SRC)
        assert src["TrickyFunc"].startswith("func TrickyFunc")

    def test_extract_ends_with_closing_brace(self) -> None:
        a = GoAdapter()
        src = a.extract_symbol_sources(_TRICKY_SRC)
        assert src["TrickyFunc"].rstrip().endswith("}")


