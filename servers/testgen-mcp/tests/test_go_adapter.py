class TestParseCoverage:
    def test_two_files_returned(self) -> None:
        a = GoAdapter()
        cov = a.parse_coverage(_COVERPROFILE)
        assert len(cov) == 2  # noqa: PLR2004

    def test_module_prefix_stripped_jobs(self) -> None:
        a = GoAdapter()
        paths = {fc.source_rel for fc in a.parse_coverage(_COVERPROFILE)}
        assert "services/api/srv/jobs/jobs.go" in paths

    def test_module_prefix_stripped_runtimes(self) -> None:
        a = GoAdapter()
        paths = {fc.source_rel for fc in a.parse_coverage(_COVERPROFILE)}
        assert "services/api/srv/runtimes/runtimes.go" in paths

    def test_jobs_total_stmts(self) -> None:
        # Two lines for jobs.go: 3 stmts + 2 stmts = 5
        a = GoAdapter()
        by_path = {fc.source_rel: fc for fc in a.parse_coverage(_COVERPROFILE)}
        assert by_path["services/api/srv/jobs/jobs.go"].total_stmts == 5  # noqa: PLR2004

    def test_jobs_covered_stmts(self) -> None:
        # Only the count=1 line (3 stmts) contributes to covered
        a = GoAdapter()
        by_path = {fc.source_rel: fc for fc in a.parse_coverage(_COVERPROFILE)}
        assert by_path["services/api/srv/jobs/jobs.go"].covered_stmts == 3  # noqa: PLR2004

    def test_jobs_percent(self) -> None:
        a = GoAdapter()
        by_path = {fc.source_rel: fc for fc in a.parse_coverage(_COVERPROFILE)}
        assert by_path["services/api/srv/jobs/jobs.go"].percent == 60.0

    def test_covered_lines_populated(self) -> None:
        # count=1 line: startLine=15, endLine=25 → 15..25 in covered_lines
        a = GoAdapter()
        by_path = {fc.source_rel: fc for fc in a.parse_coverage(_COVERPROFILE)}
        jobs = by_path["services/api/srv/jobs/jobs.go"]
        assert 15 in jobs.covered_lines
        assert 25 in jobs.covered_lines

    def test_uncovered_lines_populated(self) -> None:
        # count=0 line: startLine=30, endLine=35 → 30..35 in uncovered_lines
        a = GoAdapter()
        by_path = {fc.source_rel: fc for fc in a.parse_coverage(_COVERPROFILE)}
        jobs = by_path["services/api/srv/jobs/jobs.go"]
        assert 30 in jobs.uncovered_lines
        assert 35 in jobs.uncovered_lines

    def test_runtimes_fully_covered(self) -> None:
        a = GoAdapter()
        by_path = {fc.source_rel: fc for fc in a.parse_coverage(_COVERPROFILE)}
        rt = by_path["services/api/srv/runtimes/runtimes.go"]
        assert rt.total_stmts == 5  # noqa: PLR2004
        assert rt.covered_stmts == 5  # noqa: PLR2004
        assert rt.percent == 100.0

    def test_mode_line_skipped(self) -> None:
        a = GoAdapter()
        cov = a.parse_coverage("mode: count\n")
        assert cov == []

    def test_malformed_line_skipped(self) -> None:
        a = GoAdapter()
        raw = "mode: set\nnot_valid_at_all\n"
        cov = a.parse_coverage(raw)
        assert cov == []

    def test_custom_module_path(self) -> None:
        a = GoAdapter(module_path="example.com/myrepo")
        raw = "mode: set\nexample.com/myrepo/pkg/foo.go:1.1,5.2 2 1\n"
        cov = a.parse_coverage(raw)
        assert len(cov) == 1
        assert cov[0].source_rel == "pkg/foo.go"

    def test_no_prefix_match_kept_as_is(self) -> None:
        a = GoAdapter()
        raw = "mode: set\nother.com/repo/pkg/foo.go:1.1,5.2 2 1\n"
        cov = a.parse_coverage(raw)
        assert len(cov) == 1
        assert cov[0].source_rel == "other.com/repo/pkg/foo.go"


