class TestReferenceTests:
    def test_returns_existing_golden_files(self) -> None:
        a = GoAdapter()
        repo = "/Users/ardas/Documents/Cloudera/src/github.infra.cloudera.com/cloudera-sense"
        if not Path(repo).is_dir():
            return  # skip if repo not available
        refs = a.reference_tests(repo, "services/api/srv/jobs")
        # At least one golden file should exist in the real repo
        assert len(refs) > 0

    def test_empty_when_nothing_exists(self) -> None:
        a = GoAdapter()
        with tempfile.TemporaryDirectory() as tmp:
            refs = a.reference_tests(tmp, "nonexistent/pkg")
            assert refs == []

    def test_includes_package_test_files(self) -> None:
        a = GoAdapter()
        with tempfile.TemporaryDirectory() as tmp:
            pkg_dir = Path(tmp) / "mypkg"
            pkg_dir.mkdir()
            (pkg_dir / "mypkg_test.go").write_text("package mypkg\n")
            refs = a.reference_tests(tmp, "mypkg")
            assert "mypkg/mypkg_test.go" in refs

    def test_deduplicates(self) -> None:
        a = GoAdapter()
        with tempfile.TemporaryDirectory() as tmp:
            # Create the golden path structure so a golden file appears in both
            # the golden list AND the package dir scan
            golden_dir = Path(tmp) / "services" / "api" / "srv" / "jobs"
            golden_dir.mkdir(parents=True)
            golden_file = golden_dir / "jobs_test.go"
            golden_file.write_text("package jobs\n")
            refs = a.reference_tests(tmp, "services/api/srv/jobs")
            assert refs.count("services/api/srv/jobs/jobs_test.go") == 1

    def test_returns_posix_paths(self) -> None:
        a = GoAdapter()
        with tempfile.TemporaryDirectory() as tmp:
            pkg_dir = Path(tmp) / "mypkg"
            pkg_dir.mkdir()
            (pkg_dir / "mypkg_test.go").write_text("package mypkg\n")
            refs = a.reference_tests(tmp, "mypkg")
            for r in refs:
                assert "\\" not in r

    def test_name_attribute(self) -> None:
        a = GoAdapter()
        assert a.name == "go"


